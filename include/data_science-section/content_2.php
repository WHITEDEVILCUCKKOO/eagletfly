<script>
  (function () {
    var sec = document.getElementById('ef-ncr-section');
    if (!sec) return;

    var reveals = sec.querySelectorAll('.ef-ncr-reveal');
    var hubPills = sec.querySelectorAll('.ef-ncr-hub-pill');
    var cards = sec.querySelectorAll('.ef-ncr-card');

    function activateSection() {
      sec.classList.add('ef-ncr-active');
      reveals.forEach(function (el) {
        var delay = parseInt(el.getAttribute('data-ef-delay') || '0', 10);
        setTimeout(function () {
          el.classList.add('ef-ncr-shown');
        }, delay);
      });
    }

    if ('IntersectionObserver' in window) {
      var observer = new IntersectionObserver(
        function (entries) {
          entries.forEach(function (entry) {
            if (entry.isIntersecting) {
              activateSection();
              observer.unobserve(entry.target);
            }
          });
        },
        { threshold: 0.15 }
      );
      observer.observe(sec);
    } else {
      activateSection();
    }

    // Interactive Hub Pill Hover/Click highlights corresponding Ecosystem Cards
    hubPills.forEach(function (pill) {
      pill.addEventListener('mouseenter', function () {
        var hub = pill.getAttribute('data-ef-hub');
        hubPills.forEach(function (p) { p.classList.remove('ef-ncr-hub-active'); });
        pill.classList.add('ef-ncr-hub-active');

        cards.forEach(function (card) {
          var tags = card.getAttribute('data-ef-city-tag') || '';
          if (tags.indexOf(hub) !== -1) {
            card.classList.add('ef-ncr-card-glow');
          } else {
            card.classList.remove('ef-ncr-card-glow');
          }
        });
      });

      pill.addEventListener('mouseleave', function () {
        cards.forEach(function (card) {
          card.classList.remove('ef-ncr-card-glow');
        });
      });
    });
  })();
</script>
