<script>
  (function () {
    var sec = document.getElementById('ef-ds-v2-section');
    if (!sec) return;

    var items = sec.querySelectorAll('.ef-ds-v2-reveal');

    function triggerSection() {
      sec.classList.add('ef-ds-v2-active');
      items.forEach(function (el) {
        var d = parseInt(el.getAttribute('data-ef-delay') || '0', 10);
        setTimeout(function () {
          el.classList.add('ef-ds-v2-shown');
        }, d);
      });
    }

    if ('IntersectionObserver' in window) {
      var obs = new IntersectionObserver(
        function (entries) {
          entries.forEach(function (entry) {
            if (entry.isIntersecting) {
              triggerSection();
              obs.unobserve(entry.target);
            }
          });
        },
        { threshold: 0.15 }
      );
      obs.observe(sec);
    } else {
      triggerSection();
    }
  })();
</script>
