<script>

(function () {

    "use strict";


    /* ======================================================
       SETTINGS
    ====================================================== */

    var DESKTOP_BREAKPOINT = 1024;

    /*
     Header aur form ke beech gap
     Isko increase/decrease kar sakte ho.
    */
    var HEADER_GAP = 18;

    /*
     Agar header detect na ho paye to
     minimum fallback top gap.
    */
    var MINIMUM_TOP = 20;



    /* ======================================================
       ELEMENTS
    ====================================================== */

    var section =
        document.getElementById("klrCourseStickySection");


    if (!section) {
        return;
    }


    var container =
        section.querySelector(".klr-course-container");

    var leftColumn =
        section.querySelector(".klr-course-left");

    var rightColumn =
        section.querySelector(".klr-course-right");

    var formCard =
        section.querySelector(".klr-course-form-card");

    var placeholder =
        section.querySelector(".klr-course-form-placeholder");


    if (
        !container ||
        !leftColumn ||
        !rightColumn ||
        !formCard ||
        !placeholder
    ) {
        return;
    }


    var originalParent = rightColumn;

    var currentState = "";



    /* ======================================================
       IMPORTANT CSS
    ====================================================== */

    function importantStyle(
        element,
        property,
        value
    ) {

        element.style.setProperty(
            property,
            value,
            "important"
        );

    }



    /* ======================================================
       FIND ACTUAL STICKY HEADER HEIGHT
    ====================================================== */

    function getHeaderBottom() {

        /*
         Common WordPress / Elementor
         header selectors
        */

        var selectors = [

            ".elementor-location-header",

            "[data-elementor-type='header']",

            "#masthead",

            ".site-header",

            ".main-header",

            ".header-wrapper",

            ".header",

            "header"

        ];


        var highestBottom = 0;


        selectors.forEach(
            function (selector) {

                var headers =
                    document.querySelectorAll(selector);


                headers.forEach(
                    function (header) {

                        /*
                         Ignore header if it belongs
                         inside our course section
                        */

                        if (
                            section.contains(header)
                        ) {
                            return;
                        }


                        var styles =
                            window.getComputedStyle(header);


                        if (
                            styles.display === "none" ||
                            styles.visibility === "hidden"
                        ) {
                            return;
                        }


                        var rect =
                            header.getBoundingClientRect();


                        /*
                         Only header currently visible
                         at the top of viewport matters
                        */

                        if (
                            rect.height <= 0 ||
                            rect.bottom <= 0
                        ) {
                            return;
                        }


                        var position =
                            styles.position;


                        var isStickyHeader =
                            position === "fixed" ||
                            position === "sticky" ||
                            (
                                rect.top <= 5 &&
                                rect.bottom > 0
                            );


                        if (!isStickyHeader) {
                            return;
                        }


                        /*
                         Prevent accidentally detecting
                         a huge full-screen element
                        */

                        if (
                            rect.bottom >
                            window.innerHeight * 0.45
                        ) {
                            return;
                        }


                        if (
                            rect.bottom >
                            highestBottom
                        ) {

                            highestBottom =
                                rect.bottom;

                        }

                    }
                );

            }
        );


        /*
         Header exists:
         header bottom + clean gap

         Header doesn't exist:
         normal minimum top
        */

        if (highestBottom > 0) {

            return Math.ceil(
                highestBottom + HEADER_GAP
            );

        }


        return MINIMUM_TOP;

    }



    /* ======================================================
       CLEAR FIXED STYLES
    ====================================================== */

    function clearStickyStyles() {

        var props = [

            "position",
            "top",
            "left",
            "right",
            "bottom",
            "width",
            "max-width",
            "z-index",
            "margin",
            "max-height",
            "overflow-y"

        ];


        props.forEach(
            function (property) {

                formCard.style.removeProperty(
                    property
                );

            }
        );

    }



    /* ======================================================
       MOVE FORM BACK
    ====================================================== */

    function moveBackToColumn() {

        if (
            formCard.parentNode !==
            originalParent
        ) {

            originalParent.appendChild(
                formCard
            );

        }

    }



    /* ======================================================
       NORMAL
    ====================================================== */

    function setNormalState() {

        moveBackToColumn();


        placeholder.style.display =
            "none";

        placeholder.style.height =
            "0px";


        clearStickyStyles();


        importantStyle(
            formCard,
            "position",
            "relative"
        );


        importantStyle(
            formCard,
            "top",
            "auto"
        );


        importantStyle(
            formCard,
            "left",
            "auto"
        );


        importantStyle(
            formCard,
            "width",
            "100%"
        );


        importantStyle(
            formCard,
            "max-width",
            "100%"
        );


        currentState =
            "normal";

    }



    /* ======================================================
       FIXED UNDER HEADER
    ====================================================== */

    function setFixedState(
        rightRect,
        cardHeight,
        stickyTop
    ) {

        placeholder.style.display =
            "block";


        placeholder.style.height =
            cardHeight + "px";


        /*
         Move card to body so Elementor
         overflow / transform cannot break it
        */

        if (
            formCard.parentNode !==
            document.body
        ) {

            document.body.appendChild(
                formCard
            );

        }


        importantStyle(
            formCard,
            "position",
            "fixed"
        );


        /*
         KEY FIX:
         Dynamic header bottom
        */

        importantStyle(
            formCard,
            "top",
            stickyTop + "px"
        );


        importantStyle(
            formCard,
            "left",
            rightRect.left + "px"
        );


        importantStyle(
            formCard,
            "right",
            "auto"
        );


        importantStyle(
            formCard,
            "bottom",
            "auto"
        );


        importantStyle(
            formCard,
            "width",
            rightRect.width + "px"
        );


        importantStyle(
            formCard,
            "max-width",
            rightRect.width + "px"
        );


        importantStyle(
            formCard,
            "margin",
            "0"
        );


        /*
         Moderate z-index.
         Header normally stays above.
        */

        importantStyle(
            formCard,
            "z-index",
            "50"
        );


        /*
         If viewport is small,
         form itself can scroll.
        */

        var availableHeight =
            window.innerHeight -
            stickyTop -
            20;


        importantStyle(
            formCard,
            "max-height",
            availableHeight + "px"
        );


        importantStyle(
            formCard,
            "overflow-y",
            "auto"
        );


        currentState =
            "fixed";

    }



    /* ======================================================
       STOP AT LEFT CONTENT BOTTOM
    ====================================================== */

    function setBottomState(
        cardHeight
    ) {

        moveBackToColumn();


        placeholder.style.display =
            "none";

        placeholder.style.height =
            "0px";


        clearStickyStyles();


        var availableHeight =
            rightColumn.offsetHeight;


        var bottomTop =
            availableHeight -
            cardHeight;


        if (bottomTop < 0) {

            bottomTop = 0;

        }


        importantStyle(
            formCard,
            "position",
            "absolute"
        );


        importantStyle(
            formCard,
            "top",
            bottomTop + "px"
        );


        importantStyle(
            formCard,
            "left",
            "0"
        );


        importantStyle(
            formCard,
            "right",
            "auto"
        );


        importantStyle(
            formCard,
            "bottom",
            "auto"
        );


        importantStyle(
            formCard,
            "width",
            "100%"
        );


        importantStyle(
            formCard,
            "max-width",
            "100%"
        );


        importantStyle(
            formCard,
            "z-index",
            "20"
        );


        importantStyle(
            formCard,
            "overflow-y",
            "visible"
        );


        currentState =
            "bottom";

    }



    /* ======================================================
       MAIN UPDATE
    ====================================================== */

    function updateSticky() {


        /*
         MOBILE:
         sticky disabled
        */

        if (
            window.innerWidth <=
            DESKTOP_BREAKPOINT
        ) {

            rightColumn.style.minHeight =
                "";

            setNormalState();

            return;

        }



        /*
         Actual header position
        */

        var stickyTop =
            getHeaderBottom();



        /*
         Left content total height
        */

        var leftHeight =
            leftColumn.offsetHeight;


        rightColumn.style.minHeight =
            leftHeight + "px";



        /*
         Right column
        */

        var rightRect =
            rightColumn.getBoundingClientRect();



        /*
         Current scroll
        */

        var pageScroll =
            window.pageYOffset ||
            document.documentElement.scrollTop ||
            0;



        /*
         Container location
        */

        var containerRect =
            container.getBoundingClientRect();


        var sectionStart =
            containerRect.top +
            pageScroll;



        /*
         Keep card width synced
        */

        if (
            formCard.parentNode ===
            document.body
        ) {

            importantStyle(
                formCard,
                "width",
                rightRect.width + "px"
            );


            importantStyle(
                formCard,
                "max-width",
                rightRect.width + "px"
            );

        }



        /*
         Card height
        */

        var cardHeight =
            formCard.offsetHeight;



        /*
         Sticky starts ONLY when
         card would reach below header
        */

        var stickyStart =
            sectionStart -
            stickyTop;



        /*
         Left content bottom
        */

        var leftBottom =
            sectionStart +
            leftHeight;



        /*
         Sticky stop point
        */

        var stickyEnd =
            leftBottom -
            cardHeight -
            stickyTop;



        /* =====================================
           NORMAL
        ====================================== */

        if (
            pageScroll <=
            stickyStart
        ) {

            setNormalState();

            return;

        }



        /* =====================================
           FIXED UNDER HEADER
        ====================================== */

        if (
            pageScroll <
            stickyEnd
        ) {

            setFixedState(
                rightRect,
                cardHeight,
                stickyTop
            );

            return;

        }



        /* =====================================
           STOP
        ====================================== */

        setBottomState(
            cardHeight
        );

    }



    /* ======================================================
       REQUEST ANIMATION FRAME
    ====================================================== */

    var ticking = false;


    function requestUpdate() {

        if (!ticking) {

            window.requestAnimationFrame(
                function () {

                    updateSticky();

                    ticking = false;

                }
            );


            ticking = true;

        }

    }



    /* ======================================================
       EVENTS
    ====================================================== */

    window.addEventListener(
        "scroll",
        requestUpdate,
        {
            passive: true
        }
    );


    window.addEventListener(
        "resize",
        function () {

            currentState = "";

            requestUpdate();

        }
    );


    window.addEventListener(
        "load",
        function () {

            currentState = "";

            requestUpdate();

        }
    );



    /* ======================================================
       OBSERVE HEIGHT CHANGES
    ====================================================== */

    if (
        "ResizeObserver" in window
    ) {

        var resizeObserver =
            new ResizeObserver(
                function () {

                    requestUpdate();

                }
            );


        resizeObserver.observe(
            leftColumn
        );

    }



    /* ======================================================
       INITIAL RUNS
       Useful for Elementor/fonts/layout loading
    ====================================================== */

    setTimeout(
        function () {

            updateSticky();

        },
        100
    );


    setTimeout(
        function () {

            updateSticky();

        },
        500
    );


    setTimeout(
        function () {

            updateSticky();

        },
        1200
    );


    setTimeout(
        function () {

            updateSticky();

        },
        2500
    );


})();

</script>