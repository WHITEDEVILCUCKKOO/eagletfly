<!-- Scoped JavaScript for Scroll Animations -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const efRdsObserverOptions = {
            root: null,
            rootMargin: '0px',
            threshold: 0.15
        };

        const efRdsObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('ef-rds-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, efRdsObserverOptions);

        document.querySelectorAll('.ef-rds-fade-in').forEach(card => {
            efRdsObserver.observe(card);
        });
    });
</script>
