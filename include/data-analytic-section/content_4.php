<!-- Scoped JavaScript for Accordion Toggle Functionality -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const accItems = document.querySelectorAll('.ef-acc-item');

        accItems.forEach(item => {
            const question = item.querySelector('.ef-acc-question');
            const answer = item.querySelector('.ef-acc-answer');
            const icon = item.querySelector('.ef-acc-icon');

            question.addEventListener('click', () => {
                const isActive = item.classList.contains('ef-acc-active');

                // Optional: Close all other items (accordion behavior)
                // accItems.forEach(otherItem => {
                //     otherItem.classList.remove('ef-acc-active');
                //     otherItem.querySelector('.ef-acc-answer').style.maxHeight = null;
                //     otherItem.querySelector('.ef-acc-icon').textContent = '+';
                // });

                if (isActive) {
                    item.classList.remove('ef-acc-active');
                    answer.style.maxHeight = null;
                    icon.textContent = '+';
                } else {
                    item.classList.add('ef-acc-active');
                    answer.style.maxHeight = answer.scrollHeight + "px";
                    icon.textContent = '×';
                }
            });
        });
    });
</script>
