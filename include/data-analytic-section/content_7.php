<!-- Scoped JavaScript for Scroll Animations -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const efEttObserverOptions = {
            root: null,
            rootMargin: '0px',
            threshold: 0.15
        };

        const efEttObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('ef-ett-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, efEttObserverOptions);

        document.querySelectorAll('.ef-ett-fade-in').forEach(card => {
            efEttObserver.observe(card);
        });
    });
</script>
