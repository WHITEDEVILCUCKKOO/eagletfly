<!-- Scoped JavaScript for Scroll Animations -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const efRcpObserverOptions = {
            root: null,
            rootMargin: '0px',
            threshold: 0.15
        };

        const efRcpObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('ef-rcp-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, efRcpObserverOptions);

        document.querySelectorAll('.ef-rcp-fade-in').forEach(card => {
            efRcpObserver.observe(card);
        });
    });
</script>
