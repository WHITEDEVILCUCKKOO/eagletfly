<!-- Scoped JavaScript for Scroll Animations -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const efPatObserverOptions = {
            root: null,
            rootMargin: '0px',
            threshold: 0.15
        };

        const efPatObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('ef-pat-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, efPatObserverOptions);

        document.querySelectorAll('.ef-pat-fade-in').forEach(card => {
            efPatObserver.observe(card);
        });
    });
</script>
