<!-- Scoped JavaScript for Scroll Animations -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        const efPstObserverOptions = {
            root: null,
            rootMargin: '0px',
            threshold: 0.15
        };

        const efPstObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('ef-pst-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, efPstObserverOptions);

        document.querySelectorAll('.ef-pst-fade-in').forEach(card => {
            efPstObserver.observe(card);
        });
    });
</script>
