<script>
document.addEventListener("DOMContentLoaded", function () {
    const eagletflyThemeObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('eagletfly-theme-show');
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.15 });

    document.querySelectorAll('.eagletfly-theme-fade').forEach(el => {
        eagletflyThemeObserver.observe(el);
    });
});
</script>